function ka(cid)
    if not isCreature(cid) then
        return
    end
    doCreatureSay(cid, 'Ka...!', TALKTYPE_ORANGE_1)
    addEvent(function() ma(cid) end, 300)
end

function ma(cid)
    if not isCreature(cid) then
        return
    end
    doCreatureSay(cid, 'Me...!', TALKTYPE_ORANGE_1)
    addEvent(function() ha2(cid) end, 200)
end

function ha2(cid)
    if not isCreature(cid) then
