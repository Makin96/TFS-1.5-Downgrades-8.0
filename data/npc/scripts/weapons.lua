function msgcontains(txt, str)
  	return (string.find(txt, str) and not string.find(txt, '(%w+)' .. str) and not string.find(txt, str .. '(%w+)'))
end


function onCreatureSay(cid, type, msg)
  	msg = string.lower(msg)

  	if (msgcontains(msg, 'hi') and (focus == 0)) and getDistanceToCreature(cid) < 4 then
  		selfSay('Hello, ' .. getCreatureName(cid) .. '! I buy all weapons what you can see here.')
  		focus = cid
  		talk_start = os.clock()

  	elseif msgcontains(msg, 'hi') and (focus ~= cid) and getDistanceToCreature(cid) < 4 then
  		selfSay('Sorry, ' .. getCreatureName(cid) .. '! I talk to you in a minute.')

	elseif focus == cid then
		talk_start = os.clock()

		if msgcontains(msg, 'rines') then
			sell(cid,2382,getCount(msg),10)
		elseif msgcontains(msg, 'staff') then
			sell(cid,2398,getCount(msg),100)
		elseif msgcontains(msg, 'castet') then
			sell(cid,2432,getCount(msg),1000)
		elseif msgcontains(msg, 'saw') then
			sell(cid,2417,getCount(msg),500)
		elseif msgcontains(msg, 'full staff') then
		sell(cid,2434,getCount(msg),2000)
		elseif msgcontains(msg, 'goku staff') then
		sell(cid,2401,getCount(msg),5000)
		elseif msgcontains(msg, 'nunhacko') then
		sell(cid,2391,getCount(msg),10000)



		elseif msgcontains(msg, 'bye') and getDistanceToCreature(cid) < 4 then
			selfSay('Good bye, ' .. getCreatureName(cid) .. '!')
			focus = 0
			talk_start = 0
		end
	end
end

function onThink()
	doNpcSetCreatureFocus(focus)
  	if (os.clock() - talk_start) > 45 then
  		if focus > 0 then
  			selfSay('Next Please...')
  		end
  			focus = 0
  	end
 	if focus ~= 0 then
 		if getDistanceToCreature(focus) > 5 then
 			selfSay('Good bye then.')
 			focus = 0
 		end
 	end
end
